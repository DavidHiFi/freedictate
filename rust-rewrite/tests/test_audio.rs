//! Offline parity port of tests/test_audio.rs. No audio device is opened:
//! the capture chain is driven with synthetic blocks the way PortAudio
//! would call it, then flushed and measured.

use freedictate_rust::audio::{simulate_capture, RATE};

/// Helper: generate synthetic mono samples at frequency with 0.5 amplitude
/// (matching Python test_audio.py).
fn signal_tone(freq: f32, rate: u32, seconds: f32) -> Vec<f32> {
    let total = (rate as f32 * seconds) as usize;
    (0..total)
        .map(|i| 0.5 * (2.0 * std::f32::consts::PI * freq * i as f32 / rate as f32).sin())
        .collect()
}

#[test]
fn n_seconds_in_gives_exactly_n_times_16000_samples() {
    for &rate in &[48000, 44100, 96000, 32000] {
        for seconds in 1..=5 {
            let data = signal_tone(100.0, rate, seconds as f32);
            let (out, secs) = simulate_capture(rate, 1, 800, &data);
            let expected_samples = seconds * 16000;
            assert!(
                (out.len() as i64 - expected_samples as i64).abs() <= 1,
                "rate={rate} seconds={seconds}: expected ~{expected_samples}, got {}",
                out.len()
            );
            assert!(
                (secs - seconds as f64).abs() < 0.01,
                "rate={rate} seconds={seconds}: duration off"
            );
        }
    }
}

#[test]
fn odd_block_sizes_do_not_drift() {
    let data = signal_tone(100.0, 44100, 3.0);
    let (out, secs) = simulate_capture(44100, 1, 441, &data);
    assert_eq!(out.len(), 3 * RATE as usize);
    assert!((secs - 3.0).abs() < 0.01);
}

#[test]
fn content_above_8k_is_filtered_not_aliased() {
    // 12 kHz tone aliased to 4 kHz would appear if not filtered.
    let data = signal_tone(12000.0, 48000, 2.0);
    let (out, _secs) = simulate_capture(48000, 1, 800, &data);
    let body_start = 1000.min(out.len());
    let body_end = out.len().saturating_sub(1000).max(body_start);
    let body = &out[body_start..body_end];
    let rms: f32 = (body.iter().map(|s| s * s).sum::<f32>() / body.len() as f32).sqrt();
    assert!(rms < 0.005, "12 kHz tone did not filter: RMS={rms}");
}

#[test]
fn in_band_tone_survives() {
    // 1 kHz tone should pass through unharmed.
    let data = signal_tone(1000.0, 48000, 2.0);
    let (out, _secs) = simulate_capture(48000, 1, 800, &data);
    let body_start = 1000.min(out.len());
    let body_end = out.len().saturating_sub(1000).max(body_start);
    let body = &out[body_start..body_end];
    let rms: f32 = (body.iter().map(|s| s * s).sum::<f32>() / body.len() as f32).sqrt();
    let expected = 0.5 / 2.0_f32.sqrt();
    assert!(
        (rms - expected).abs() < 0.01,
        "1 kHz tone RMS={rms}, expected ~{expected}"
    );
}

