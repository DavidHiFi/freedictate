#[test]
#[ignore]
fn e2e_transcribe_wav() {
    use freedictate_rust::transcribe::{local_path, Voice};
    use std::path::Path;

    // Find the downloaded model.
    let model_name = "tiny.en";
    let model_path = local_path(model_name).expect("tiny.en model should be downloaded");
    assert!(model_path.exists(), "model file exists: {:?}", model_path);

    // Read the test WAV file generated by PowerShell.
    let wav_path = Path::new("H:/System Configuration/work/reports/fd-e2e-check.wav");
    assert!(wav_path.exists(), "test WAV should exist");

    let mut reader = hound::WavReader::open(wav_path).expect("open WAV");
    let spec = reader.spec();
    assert_eq!(spec.sample_rate, 16000, "test WAV should be 16 kHz");
    assert_eq!(spec.channels, 1, "test WAV should be mono");

    // Decode to i16 then convert to f32.
    let samples_i16: Vec<i16> = reader.samples().map(|r| r.unwrap()).collect();
    let samples_f32: Vec<f32> = samples_i16.iter().map(|s| *s as f32 / i16::MAX as f32).collect();

    // Load model and transcribe.
    let start_load = std::time::Instant::now();
    let voice = Voice::load(&model_path).expect("load model");
    let load_ms = start_load.elapsed().as_millis();

    let start_transcribe = std::time::Instant::now();
    let text = voice.transcribe(&samples_f32, Some("en")).expect("transcribe");
    let transcribe_ms = start_transcribe.elapsed().as_millis();

    println!("Model load: {} ms", load_ms);
    println!("Transcribe: {} ms", transcribe_ms);
    println!("Text: {:?}", text);

    // Verify we got some text.
    assert!(!text.is_empty() || text.len() < 60, "transcription gave: {:?}", text);

    // Clean up.
    voice.unload();
}